-- Russian (ruRU): every user-facing string of the addon, by ID key, as
-- Locales/enUS.lua has them. A plural entry has a form per answer of
-- Russian's rule: one (1, 21, 31...), few (2-4, 22-24...), many (the rest).
TC = TC or {}

local function plural(n)
    local m10, m100 = n % 10, n % 100
    if m10 == 1 and m100 ~= 11 then return "one" end
    if m10 >= 2 and m10 <= 4 and (m100 < 12 or m100 > 14) then return "few" end
    return "many"
end

